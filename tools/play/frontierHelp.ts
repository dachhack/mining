// The help of the new game's play interface: usage, then the rules as the
// player needs them. The numbers come from src/data/frontier.ts, so the text
// stays true when they are tuned.

import { campRadius } from '../../src/engine';
import {
  FRONTIER_AXE,
  FRONTIER_CROPS,
  FRONTIER_SAW_HOUSE,
  FRONTIER_MINERS,
  FRONTIER_SUGAR_SHACK,
  FRONTIER_CAMP_LEVELS,
  FRONTIER_BOARD,
  FRONTIER_CAMP_PLACE,
  FRONTIER_DEEP_CAMP,
  FRONTIER_FOODS,
  FRONTIER_LANTERN,
  FRONTIER_MARKET,
  FRONTIER_NEW_CAMP_COST,
  FRONTIER_PEN,
  FRONTIER_PICKAXE,
  FRONTIER_DEFENSE,
  FRONTIER_DEFENSE_MIN_LEVEL,
  FRONTIER_DRAGON,
  FRONTIER_GAS,
  FRONTIER_PUMP,
  FRONTIER_RAID,
  FRONTIER_RAIN,
  FRONTIER_WATER,
  FRONTIER_RECIPES,
  FRONTIER_RUN,
  FRONTIER_SAPLINGS,
  FRONTIER_SMELTER,
  FRONTIER_SHIFT,
  FRONTIER_SURFACE,
} from '../../src/data/frontier';
import { ENGINE_VERSION } from '../../src/engine';

/** "15 wood, 15 grass". */
function cost(stacks: { item: string; count: number }[]): string {
  return stacks.map((s) => `${s.count} ${s.item}`).join(', ');
}

export function frontierHelpText(): string {
  const s = FRONTIER_SHIFT;
  // "1 apple, else 2 grass, else 1 animal"
  const foods = FRONTIER_FOODS.map((f) => `${f.count} ${f.item}`).join(', else ');
  const levels = FRONTIER_CAMP_LEVELS.map(
    (level, i) =>
      `  Level ${i + 1}: ring ${level.radius}; mines ${level.addsBlocks.length === 0 ? 'nothing new' : `${level.addsBlocks.join(', ')}${i === 0 ? '' : ' and all of the above'}`}${level.upgradeCost.length > 0 ? `; upgrade costs ${cost(level.upgradeCost)}` : ''}`,
  );
  return [
    `Mining Game: the text play interface (engine ${ENGINE_VERSION})`,
    '',
    'Usage:',
    '  npm run play -- --seed 7 -i                    play seed 7, choice by choice',
    '  npm run play -- --seed 7 --log run.json -i     the same, saved to run.json after every step;',
    '                                                 run it again to carry on',
    '  npm run play -- --log run.json --do "tap 16,15; end"   take choices, then show the view',
    '  npm run play -- --replay run.json              replay a saved run and show where it ended',
    '  npm run play:old -- --help                     the old game (until it is removed)',
    '',
    'Choices: "tap X,Y", "place X,Y", "upgrade N", "demolish N", "smelter N", "make R", "lantern N",',
    '"sell ITEM N", "buy ITEM N", "plant X,Y sapling", "plant X,Y appleSapling", "saw X,Y", "end", "close",',
    '"undo", "look X,Y", or the number of a',
    'listed choice. Separate several with ";".',
    '',
    'The rules:',
    `- A run lasts ${FRONTIER_RUN.shifts} shifts. Your score is the coins you hold at the end.`,
    '- The map is a square of ground seen from above. Your camps light a ring around them;',
    '  the rest is fog. A square once lit but out of range now is shown, but cannot be mined.',
    `- A shift has ${s.taps} taps. Every action that does something costs 1 tap. "end" ends the`,
    '  shift (unused taps are lost); then the world moves on.',
    '- A tap takes what is on a square first: an animal (1 animal), grass (1 grass), an apple',
    `  (1 apple a tap, ${FRONTIER_SURFACE.applesPerTree} on a tree), or a tree (${FRONTIER_SURFACE.woodPerTree} wood; an apple tree once its apples are gone).`,
    '  Then it mines the top block, which gives what the block gives (stone, clay, coal...).',
    '- The level rule: a square can only be mined if none of its four neighbours is more than',
    '  1 level higher. Dig wide, not deep.',
    `- A camp stands on a level 3 x 3, lit, not over another camp, no deeper than depth ${FRONTIER_CAMP_PLACE.maxDepth}. Its ground is never mined.`,
    `  A new camp costs ${cost(FRONTIER_NEW_CAMP_COST)}. A camp can be demolished once other camps' rings`,
    '  cover its 3 x 3; it gives nothing back.',
    ...levels,
    `- At the end of each shift: animals take ${s.animalStepsPerShift} steps (a new one walks in every ${s.animalEveryShifts} shifts);`,
    `  an apple tree picked bare has its apples back ${s.appleRegrowShifts} shifts later; a felled tree grows back`,
    `  ${s.treeRegrowShifts} shifts later, unless its square was mined or a camp stands on it; upkeep is paid:`,
    `  ${s.woodEveryShift} wood every shift, 1 food (${foods}) every ${s.foodEveryShifts} shifts, and 1 more wood`,
    `  every ${s.campWoodEveryShifts} shifts for each camp after the first.`,
    `- Each item of upkeep you cannot pay costs ${s.tapsLostPerUnpaid} taps of the next shift. The run never ends early for it.`,
    `- Hazards. Rain: on about ${Math.round(FRONTIER_RAIN.chance * 100)}% of nights it rains, and about ${Math.round(FRONTIER_RAIN.fillChance * 100)}% of the low spots`,
    '  (dug squares lower than a neighbour, with no neighbour lower) are filled by 1 block of dirt or clay.',
    "  What was on top is buried, not lost: dig it out again. A camp's ground is never filled.",
    `  Water: opening a water pocket that leaves a square at depth ${FRONTIER_WATER.fromDepth} or more floods it and the dug squares`,
    `  joined to it at that depth or deeper (up to ${FRONTIER_WATER.maxSquares}). A flooded square (~) cannot be mined or built on.`,
    `  Buy a pump at the market; "tap X,Y" on the water sets it (P). It drains ${FRONTIER_PUMP.drainPerShift} squares a night, farthest`,
    '  first, then comes back to your store. A tap on a pump picks it up.',
    `  Gas: opening a gas pocket at depth ${FRONTIER_GAS.fromDepth} or more explodes ${Math.round(FRONTIER_GAS.explodeChance * 100)}% of the time: it blows the top block off`,
    `  the squares within ${FRONTIER_GAS.blastRadius} (where the level rule allows; nothing gained) and sets fire (*) to what can burn within ${FRONTIER_GAS.fireRadius}:`,
    '  grass, trees, stumps, saplings and camps. A tap puts a fire out. A fire left at End shift spreads to what can',
    '  burn beside it, then burns its square out (grass and trees grow back later; a camp loses one upgrade).',
    '  A fire no camp lights burns out without spreading.',
    `  Dragons (D): from shift ${FRONTIER_DRAGON.fromShift}, about 1 night in ${Math.round(1 / FRONTIER_DRAGON.chance)} one flies in at the edge (at most ${FRONTIER_DRAGON.most}). Each night it flies`,
    `  ${FRONTIER_DRAGON.steps} squares in a straight line (any of 8 ways, bouncing off the edge), eats an animal beside it (or one from the pen of the camp it is on) and the apples round it,`,
    `  and sometimes sets a fire. In the day it rests for ${FRONTIER_DRAGON.restMines[0]} to ${FRONTIER_DRAGON.restMines[1]} blocks mined, then flies a square on along its heading.`,
    '  It stays until "tap X,Y" on it with a sword drives it off ("make sword" at a smelter,',
    '  or buy one at the market from a level-3 camp). The sword is kept.',
    `  Marauders: from shift ${FRONTIER_RAID.fromShift}, about ${Math.round(FRONTIER_RAID.chance * 100)}% of nights they raid one camp at random. Their strength is`,
    `  ${FRONTIER_RAID.strengthFromDepth.map((st) => `${st.strength} from depth ${st.depth}`).join(', ')} (your deepest square). A camp with that many`,
    '  levels of defenses turns them away. Otherwise each point short steals ' +
      `${Math.round(FRONTIER_RAID.stealShare * 100)}% of each stack (never coins or tools)`,
    `  and tears down ${FRONTIER_RAID.upgradesPerShortfall} upgrades (lantern, pen and its animals, smelter, then levels). "defend N" builds camp N's`,
    `  next defenses (1 tap; camp level ${FRONTIER_DEFENSE_MIN_LEVEL} or more): ${FRONTIER_DEFENSE.map((d) => `${d.name} (${cost(d.cost)})`).join(', ')}.`,
    '- "close" closes the mine: the run ends.',
    `- "smelter N" builds a smelter at camp N (level ${FRONTIER_SMELTER.minLevel} or more; ${cost(FRONTIER_SMELTER.cost)}; one a camp, lost with it).`,
    `  With a smelter anywhere, "make R" makes recipe R: ${FRONTIER_RECIPES.filter(
      (r) => r.needsSmelter,
    )
      .map((r) => `${r.id} (${cost(r.inputs)} -> ${r.output.count} ${r.output.item})`)
      .join(', ')}.`,
    `  While you hold an iron pickaxe, every mining tap yields ${FRONTIER_PICKAXE.yieldTimes} times as much (a second adds nothing).`,
    `  While you hold an iron drill, iron and copper ore can be mined on any camp's ground; a steel drill also mines`,
    `  crystal, rare ore and relics. No camp level mines those. The market sells both once your best camp is level 3.`,
    `  "lantern N" hangs a copper lantern from your store at camp N: its ring grows by ${FRONTIER_LANTERN.ringBonus} (one a camp, lost with it).`,
    '  Each costs 1 tap.',
    `- The market opens every ${FRONTIER_MARKET.everyShifts.join(', ')} shifts while your best camp is level 1, 2, 3, ...`,
    '  (on the shifts that are multiples of that), after the night and before the day. "sell ITEM N" sells N lots',
    '  for coins, "buy ITEM N" buys N lots, "take ID" takes a contract; none costs a tap. "leave" closes the market',
    '  and the day starts. Nothing else can be done while it is open, and it does not open again until the next market day.',
    `- Farming: cut grass grows back ${FRONTIER_SHIFT.grassRegrowShifts} shifts later if grass grows beside it (a patch cut bare stays bare).`,
    '  Saplings, apple saplings and maple saplings come only from the market.',
    `  "plant X,Y sapling" plants one on lit surface dirt or a stump (1 tap): a tree in ${FRONTIER_SAPLINGS.saplingGrowShifts} shifts,`,
    `  an apple tree in ${FRONTIER_SAPLINGS.appleSaplingGrowShifts}, a maple tree in ${FRONTIER_SAPLINGS.mapleSaplingGrowShifts}. Mining its square digs it out.`,
    `  Seeds (${FRONTIER_CROPS.map((c) => `${c.seed}: ${c.yield} ${c.crop} after ${c.growShifts} shifts`).join('; ')}) are sown the same way, on bare dirt;`,
    '  a tap harvests a ripe crop; one still growing is left be. Grains and vegetables are food, and sell.',
    `  A maple holds ${FRONTIER_SURFACE.sapPerTree} sap, 1 a tap, and fills again as an apple tree does; then a tap fells it.`,
    `- An axe in your store fells a tree for ${FRONTIER_AXE.woodPerTree} wood, not ${FRONTIER_SURFACE.woodPerTree}. "saw X,Y" builds a saw house on lit, bare, undug ground`,
    `  (${cost(FRONTIER_SAW_HOUSE.cost)}; 1 tap): trees within ${campRadius(FRONTIER_SAW_HOUSE.radiusOfLevel)} squares of it give ${FRONTIER_SAW_HOUSE.bonus} more wood. Its square is never mined.`,
    `- Miners ("buy miner N", ${FRONTIER_MARKET.buyPrices.find((l) => l.item === FRONTIER_MINERS.item)?.coins ?? 0} coins each, up to ${FRONTIER_MINERS.most}) give ${FRONTIER_MINERS.levels.map((l) => l.taps).join(', ')} taps a shift; each eats ${FRONTIER_MINERS.foodEach} food when the crew eats.`,
    `  With 2 or more, "area X,Y" digs every diggable square of the 3 x 3 round X,Y for the lesser of ${FRONTIER_MINERS.levels.map((l) => l.areaCost ?? '-').join(', ')} taps and the squares dug.`,
    '- "dirt X,Y" fills a dug square with one block of dirt, from nothing (1 tap); not beside a deeper square.',
    `  "shack X,Y" builds a sugar shack the same way (${cost(FRONTIER_SUGAR_SHACK.cost)}; 1 tap): while one stands, "make syrup" boils 3 sap into 1 syrup.`,
    `- "pen N" builds an animal pen at camp N (level ${FRONTIER_PEN.minLevel} or more; ${cost(FRONTIER_PEN.cost)}; one a camp; lost with it, its animals back to the store).`,
    `  "penin N" / "penout N" moves an animal from the store into it or back (up to ${FRONTIER_PEN.capacity}). Penned animals are never eaten.`,
    `  A pen with 2 or more and room breeds one every ${FRONTIER_PEN.breedEveryShifts} shifts, eating ${FRONTIER_PEN.hayPerBirth} hay; "make hay" turns 3 grass into 1 hay.`,
    `- Contracts: while the market is open the board offers up to ${FRONTIER_BOARD.perTier} surface and ${FRONTIER_BOARD.perTier} other contracts of each open tier ("take ID").`,
    `  Tier 1's surface contracts (wood, hay, animals, apples, syrup, lumber, crops, mushrooms) and a small clay and stone one (stone from a level-2 camp; one of these on every board until a level-3 camp) are offered from the first market day; the rest of tier 1 opens with a level ${FRONTIER_BOARD.tier1Level} camp,`,
    '  Only contracts the world can fill are offered: the ground, your store and smelting hold all they ask for (what grows back always counts).',
    "  tier 2 after a tier-1 contract is delivered, tier 3 after a tier-2. Hold as many as your best camp's level;",
    '  "deliver ID" on any shift once you hold everything it asks for pays its coins; "drop ID" gives it up (no tap, even with none left).',
    '  At the market, "fill ID" fills a contract on the board at once if your store holds everything it asks for (it',
    '  needs no free place), and "deliver ID" delivers one held; neither costs a tap there.',
    '  The view names your phase and goal.',
    `- "deep X,Y" places a deep camp on any lit 3 x 3 whose deepest square is at depth ${FRONTIER_DEEP_CAMP.minDepth} or more: its concrete foundation digs the other squares down to it (${cost(FRONTIER_DEEP_CAMP.cost)}; the market sells the kit after a tier-1 contract).`,
    `  Its ring is ${FRONTIER_DEEP_CAMP.radius}; it mines as a level ${FRONTIER_DEEP_CAMP.level} camp and is never upgraded.`,
    '- "undo" takes back your last action in this shift and gives the tap back. Catching an',
    '  animal and picking an apple cannot be undone, and nothing before the shift began can.',
  ].join('\n');
}
